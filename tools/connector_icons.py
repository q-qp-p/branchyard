PATH = re.compile(r'<path d="([^"]+)"')
TITLE = re.compile(r"<title>([^<]+)</title>")


def build(package: Path) -> str:
    meta = json.loads((package / "package.json").read_text())
    if meta.get("license") != "CC0-1.0":
        raise SystemExit(f"simple-icons {meta.get('version')} is not CC0-1.0")
    symbols = []
    for connector, slug in sorted(ICONS.items()):
        svg = (package / "icons" / f"{slug}.svg").read_text()
        path = PATH.search(svg)
        title = TITLE.search(svg)
        if not path or not title:
            raise SystemExit(f"{slug}.svg is not a single-path icon")
        symbols.append(
            f'<symbol id="ci-{connector}" viewBox="0 0 24 24"><title>{title.group(1)}</title>'
            f'<path fill="currentColor" d="{path.group(1)}"/></symbol>'
        )
    head = (
        f"<!-- Generated by tools/connector_icons.py from Simple Icons {meta['version']}"
        ", CC0-1.0. The marks are their owners' trademarks,"
        " shown only to name the service a connector reaches. Do not edit. -->"
    )
    return head + '\n<svg xmlns="http://www.w3.org/2000/svg">\n' + "\n".join(symbols) + "\n</svg>\n"


def main(argv: list[str]) -> int:
    if argv == ["--check"]:
        text = SPRITE.read_text()
        ids = set(re.findall(r'<symbol id="ci-([^"]+)"', text))
        missing = sorted(set(ICONS) - ids)
        if missing:
            print(f"connector-icons.svg lacks {missing}; regenerate it", file=sys.stderr)
            return 1
        return 0
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    SPRITE.write_text(build(Path(argv[0])))
    print(f"wrote {SPRITE.relative_to(ROOT)} ({len(ICONS)} connectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
