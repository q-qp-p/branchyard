#!/usr/bin/env python3
"""Build the console's connector icon sprite from Simple Icons.

Simple Icons (https://simpleicons.org) publishes brand marks as single-path
SVGs under CC0-1.0; the marks themselves remain their owners' trademarks and
are shown only to name the service a connector reaches. The sprite draws
each mark with `currentColor`, so icons take the console's ink and never its
brand colour, and sit in the page like its other icons.

Usage: python3 tools/connector_icons.py PATH/TO/simple-icons/package
       python3 tools/connector_icons.py --check

`npm pack simple-icons@VERSION` and untar it to get the package directory.
The sprite is crates/branchyard-server/src/companion/assets/connector-icons.svg;
each symbol's id is `ci-<connector id>`. A connector id the sprite lacks
shows its initial instead.
"""

