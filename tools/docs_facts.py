#!/usr/bin/env python3
"""Documentation facts derived from the code, not typed by hand.

Counts, lists and matrices that the code already knows (how many files are
vendored, how many derivatives follow how many vendored sources, which crates
exist, how many tests there are, which environment prefixes the runtime
strips, which routes the server registers, which exit status `by` ends with
for each error kind) are computed
here from the source of truth and written in two places:

- docs/facts.json, the full set, committed so a change shows in review;
- every Markdown region marked <!-- fact:NAME -->...<!-- /fact --> (a marker
  directly after a backtick is documentation of the syntax and is skipped),
  whose text is replaced by the fact's rendering.

    python3 tools/docs_facts.py --write   recompute and rewrite both
    python3 tools/docs_facts.py --check   fail on any difference (CI)
    python3 tools/docs_facts.py --tests   print the test count per crate (not committed)

--check also fails when a server route is mentioned in neither docs/server.md
nor docs/surfaces.md,
unless tools/docs_facts_allow.txt lists it. That list is a ratchet: an entry
that has become documented must be removed, so it only ever shrinks.

Tables generated by Rust keep their own freshness tests (docs/compatibility.md
by `cargo test -p branchyard-harness`, catalog/*.toml by
`cargo test -p branchyard-controls catalog`); see CONTRIBUTING.md. The harness
status table in docs/status.md is read from docs/compatibility.md's table (which
already carries the qualification reports' results) rather than from a second
copy of the registry.
The test count is not a fact here. Almost every change adds a test, so a
committed count changed in almost every pull request, and any two open pull
requests conflicted on it. `--tests` prints it instead: every `#[test]` and
`#[tokio::test]` attribute in `src` and `tests`, feature-gated files and
modules included. It is not the number a default `cargo test --workspace` runs.
No network, no build: everything here is read from files.
"""

import argparse
import json
import re
import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / "docs" / "facts.json"
ALLOW = ROOT / "tools" / "docs_facts_allow.txt"
REGION = re.compile(r"(?<!`)<!-- fact:([A-Za-z0-9_.-]+) -->(.*?)<!-- /fact -->", re.S)
TEST = re.compile(r"^[ \t]*#\[(?:tokio::)?test(?:\([^\n]*\))?\]", re.M)
IGNORE = re.compile(r"^[ \t]*#\[ignore\b", re.M)
COMPAT = ROOT / "docs" / "compatibility.md"
UNESCAPED_BAR = re.compile(r"(?<!\\)\|")
HARNESS_CELL = re.compile(r"^(.*?) \(`([^`]+)`\)$")
LIVE_RUN = re.compile(r"^\[(\d+) of (\d+) pass\]\(([^)]+)\), (\d{4}-\d{2}-\d{2}), (.+)$")
ROUTE = re.compile(r'\.route\(\s*"([^"]+)"')
METHODS = re.compile(r"\b(get|post|put|patch|delete)\(")


def markdown_files():
    return sorted(ROOT.glob("*.md")) + sorted((ROOT / "docs").rglob("*.md"))


def rust_files(directory):
    return sorted(p for p in directory.rglob("*.rs") if "target" not in p.parts)


def workspace_crates():
    cargo = tomllib.loads((ROOT / "Cargo.toml").read_text())
    crates = []
    for member in cargo["workspace"]["members"]:
        manifest = tomllib.loads((ROOT / member / "Cargo.toml").read_text())
        crates.append({"name": manifest["package"]["name"], "path": member})
    return sorted(crates, key=lambda c: c["name"])


def vendor_facts():
    lock = json.loads((ROOT / "vendor.lock.json").read_text())
    by_source = Counter(entry["path"].split("/")[1] for entry in lock["files"])
    patches = json.loads((ROOT / "vendor.patches.json").read_text()).get("patches", [])
    return {
        "files": len(lock["files"]),
        "by_source": dict(sorted(by_source.items())),
        "patched": len(patches),
    }


def derivative_facts():
    """Derivatives and the vendored sources they follow, as tools/verify_derivatives.py counts them."""

    def load(name):
        return json.loads((ROOT / "patches" / name).read_text())

    scion, orca, ports = (load(n) for n in ("scion-provision.json", "orca-worktree.json", "ports.json"))
    port_paths = [d["path"] for d in ports["derivatives"]]
    return {
        "scion": {
            "derivatives": len(scion["derivatives"]),
            "sources": sum(len(d["from"]) for d in scion["derivatives"]),
            "rewritten": len(scion.get("rewritten", [])),
        },
        "orca": {
            "derivatives": len(orca["derivatives"]),
            "sources": sum(len(d["from"]) for d in orca["derivatives"]),
        },
        "ports": {
            "derivatives": len(ports["derivatives"]),
            "sources": sum(len(s) for d in ports["derivatives"] for s in d["from"].values()),
            "rust": sum(p.endswith(".rs") for p in port_paths),
            "catalogs": sum(p.endswith(".toml") for p in port_paths),
        },
    }


def test_facts(crates):
    per_crate = {}
    for crate in crates:
        tests = ignored = 0
        for directory in ("src", "tests"):
            for path in rust_files(ROOT / crate["path"] / directory):
                text = path.read_text(errors="replace")
                tests += len(TEST.findall(text))
                ignored += len(IGNORE.findall(text))
        per_crate[crate["name"]] = {"tests": tests, "ignored": ignored}
    return {
        "total": sum(c["tests"] for c in per_crate.values()),
        "ignored": sum(c["ignored"] for c in per_crate.values()),
        "by_crate": per_crate,
    }


def http_facts():
    routes = set()
    for path in rust_files(ROOT / "crates" / "branchyard-server" / "src"):
        routes.update(ROUTE.findall(path.read_text(errors="replace")))
    return {"route_count": len(routes), "routes": sorted(routes)}


def rust_string(literal):
    """The text of a Rust string literal's body: a `\\` line continuation
    skips the newline and the next line's indentation, `\\"` is a quote."""
    text = re.sub(r"\\\n\s*", "", literal)
    return text.replace('\\"', '"').replace("\\\\", "\\")


def exit_facts():
    """`by`'s exit statuses, what each means and the error kinds that end with it, from the CLI's own
    table (crates/branchyard-cli/src/errors.rs: `Exit`, `EXITS`, `KINDS`)."""
    text = (ROOT / "crates/branchyard-cli/src/errors.rs").read_text()
    enum = re.search(r"pub enum Exit \{(.*?)\n\}", text, re.S)
    meanings = re.search(r"const EXITS: \[\(Exit, &str\); \d+\] = \[(.*?)\n\];", text, re.S)
    kinds = re.search(r"const KINDS: &\[\(&str, Exit\)\] = &\[(.*?)\n\];", text, re.S)
    if not (enum and meanings and kinds):
        raise SystemExit("docs_facts: Exit, EXITS or KINDS not found in crates/branchyard-cli/src/errors.rs")
    codes = {name: int(code) for name, code in re.findall(r"^\s*(\w+) = (\d+),", enum.group(1), re.M)}
    said = {
        name: rust_string(body)
        for name, body in re.findall(r'\(\s*Exit::(\w+),\s*"((?:[^"\\]|\\.)*)"', meanings.group(1), re.S)
    }
    by_exit = {name: [] for name in codes}
    for kind, name in re.findall(r'\("([a-z_]+)", Exit::(\w+)\)', kinds.group(1)):
        by_exit[name].append(kind)
    if set(said) != set(codes):
        raise SystemExit("docs_facts: EXITS does not describe every Exit in crates/branchyard-cli/src/errors.rs")
    return [
        {"code": codes[name], "name": name, "meaning": said[name], "kinds": sorted(by_exit[name])}
        for name in sorted(codes, key=codes.get)
    ]


def exit_table(exits):
    """docs/cli.md's exit-status table."""
    rows = ["| Status | Meaning | `--json` kinds |", "|---|---|---|"]
    for exit in exits:
        kinds = ", ".join(f"`{kind}`" for kind in exit["kinds"]) or "—"
        rows.append(f"| {exit['code']} | {exit['meaning']} | {kinds} |")
    return "\n\n" + "\n".join(rows) + "\n\n"


def snake_case(name):
    """CamelCase to snake_case, as serde's `rename_all = "snake_case"` does."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def stage_facts():
    """What a branch needs from a person, row by row in precedence order, from the engine's own
    table (crates/branchyard/src/stage.rs: `STAGES`)."""
    text = (ROOT / "crates/branchyard/src/stage.rs").read_text()
    table = re.search(r"pub const STAGES: \[\(Reason, Lane, &str\); (\d+)\] = \[(.*?)\n\];", text, re.S)
    if not table:
        raise SystemExit("docs_facts: STAGES not found in crates/branchyard/src/stage.rs")
    rows = re.findall(r'\(\s*Reason::(\w+),\s*Lane::(\w+),\s*"((?:[^"\\]|\\.)*)"', table.group(2), re.S)
    if len(rows) != int(table.group(1)):
        raise SystemExit("docs_facts: a row of STAGES in crates/branchyard/src/stage.rs did not parse")
    return [
        {"reason": snake_case(reason), "lane": snake_case(lane), "condition": rust_string(body)}
        for reason, lane, body in rows
    ]


def stage_table(stages):
    """docs/concepts.md's table of what a branch needs from you."""
    rows = ["| Reason | Lane | Condition |", "|---|---|---|"]
    for stage in stages:
        rows.append(f"| `{stage['reason']}` | `{stage['lane']}` | {stage['condition']} |")
    return "\n\n" + "\n".join(rows) + "\n\n"


def runtime_facts():
    text = (ROOT / "crates/branchyard-runtime/src/lib.rs").read_text()
    match = re.search(r"const DEFAULT_STRIP: \[&str; \d+\] = \[(.*?)\];", text, re.S)
    if not match:
        raise SystemExit("docs_facts: DEFAULT_STRIP not found in branchyard-runtime")
    return {"strip_prefixes": re.findall(r'"([^"]+)"', match.group(1))}


def profile_facts():
    """Every driver profile as docs/compatibility.md lists it, with the live run behind its qualification.

    That page is generated from the harness registry and docs/qualification/*.json by a Rust example
    with its own freshness test, so its main table is the one place the two meet; this reads the table
    and adds the status word docs/status.md defines.
    """
    header, profiles = None, []
    for line in COMPAT.read_text().splitlines():
        if not line.startswith("|"):
            if header and profiles:
                break
            continue
        cells = [c.strip() for c in UNESCAPED_BAR.split(line.strip())[1:-1]]
        if cells[:2] == ["Harness", "Profile"]:
            header = cells
            continue
        if header is None or len(cells) != len(header) or set(cells[0]) <= set("-: "):
            continue
        row = dict(zip(header, cells, strict=True))
        name = HARNESS_CELL.match(row["Harness"])
        if not name:
            raise SystemExit(f"docs_facts: cannot read the harness cell {row['Harness']!r} in docs/compatibility.md")
        profile = row["Profile"].strip("`")
        run = LIVE_RUN.match(row["Live qualification"])
        entry = {
            "harness": name.group(1),
            "id": name.group(2),
            "profile": None if profile == "\u2014" else profile,
            "role": row["Role"],
            "permissions_answered": row["Perm. answered"],
            "steer": row["Steer"],
        }
        if entry["profile"] is None:
            entry["status"] = "not built"
        elif run:
            passed, total, report, day, version = run.groups()
            entry["live"] = {
                "passed": int(passed),
                "total": int(total),
                "report": report,
                "date": day,
                "version": version,
            }
            entry["status"] = "live-qualified" if passed == total else "partial"
        else:
            entry["status"] = "unqualified"
        profiles.append(entry)
    if not profiles:
        raise SystemExit("docs_facts: no profile table found in docs/compatibility.md")
    return profiles


def prometheus_name(name, unit, counter):
    """The name `GET /metrics` gives an instrument: the translation
    `branchyard_telemetry::prometheus::prometheus_name` makes (a Rust test
    in metrics.rs checks that every family's name is in the docs)."""

    def sanitize(text):
        text = re.sub(r"[^A-Za-z0-9_]", "_", text)
        return "_" + text if text[:1].isdigit() else text

    base = sanitize(name)
    if counter and base.endswith("_total"):
        base = base[: -len("_total")]
    unit = unit.strip()
    suffix = None
    if unit and unit != "1" and not (unit.startswith("{") and unit.endswith("}")):
        suffix = {
            "s": "seconds",
            "ms": "milliseconds",
            "us": "microseconds",
            "ns": "nanoseconds",
            "By": "bytes",
            "%": "percent",
        }.get(unit, sanitize(unit.lower()))
    if suffix and not base.endswith("_" + suffix):
        base += "_" + suffix
    return base + "_total" if counter else base


def metric_facts():
    """Every metric family the server exposes, from the declarations in
    crates/branchyard-server/src/metrics.rs: name, type, unit, labels in
    the order they are written, and help."""
    text = (ROOT / "crates" / "branchyard-server" / "src" / "metrics.rs").read_text()
    consts = dict(re.findall(r'pub const (\w+): &str = "([^"]+)";', text))
    body = text[text.index("pub const FAMILIES") :]
    body = body[: body.index("\n];")]
    literal = r'"((?:[^"\\]|\\.)*)"'
    entry = re.compile(
        r"family\(\s*(\w+),\s*Kind::(\w+),\s*" + literal + r",\s*" + literal + r",?\s*\)"
        r"|histogram\(\s*(\w+),\s*" + literal + r",\s*" + literal + r",\s*\w+,?\s*\)"
    )
    order_body = text[text.index("pub fn label_order") :]
    order_body = order_body[: order_body.index("\n}\n")]
    orders = {}
    for arm in re.finditer(r"([A-Z_][A-Z_0-9 |\n]*?)\s*=>\s*&\[(.*?)\]", order_body, re.S):
        labels = re.findall(r'"([^"]+)"', arm[2])
        for const in re.findall(r"[A-Z_][A-Z_0-9]*", arm[1]):
            orders[const] = labels
    families = []
    for m in entry.finditer(body):
        if m[1]:
            const, kind, unit, help_ = m[1], m[2], m[3], m[4]
        else:
            const, kind, unit, help_ = m[5], "Histogram", m[6], m[7]
        counter = kind in ("Counter", "ObservedCounter")
        name = consts[const]
        families.append(
            {
                "name": name,
                "exposed": prometheus_name(name, rust_string(unit), counter),
                "type": "counter" if counter else "histogram" if kind == "Histogram" else "gauge",
                "unit": rust_string(unit),
                "labels": [re.sub(r"[^A-Za-z0-9_]", "_", label) for label in orders.get(const, [])],
                "help": rust_string(help_),
            }
        )
    return families


def metric_table(families):
    rows = [
        "| Metric | Type | Unit | Labels | What |",
        "|---|---|---|---|---|",
    ]
    for f in families:
        labels = ", ".join(f"`{label}`" for label in f["labels"]) or "none"
        unit = f"`{f['unit']}`" if f["unit"] else ""
        rows.append(f"| `{f['exposed']}` | {f['type']} | {unit} | {labels} | {f['help']} |")
    return "\n\n" + "\n".join(rows) + "\n\n"


def compute():
    crates = workspace_crates()
    return {
        "_comment": "Generated by tools/docs_facts.py --write. Do not edit.",
        "workspace": {"crate_count": len(crates), "crates": [c["name"] for c in crates]},
        "artifact_preview": {
            "page_cap": int(
                re.search(
                    r"if !\(1\.\.=(\d+)\)\.contains\(&self\.page\)",
                    (ROOT / "crates/branchyard-server/src/preview/mod.rs").read_text(),
                )[1]
            ),
            "row_page": int(
                re.search(
                    r"var limit = viewer \? (\d+) :",
                    (ROOT / "crates/branchyard-server/src/companion/assets/artifact-preview.js").read_text(),
                )[1]
            ),
        },
        "vendor": vendor_facts(),
        "derivatives": derivative_facts(),
        "http": http_facts(),
        "metrics": metric_facts(),
        "runtime": runtime_facts(),
        "profiles": profile_facts(),
        "cli": {"exit_codes": exit_facts()},
        "stages": stage_facts(),
        "document_skills": json.loads((ROOT / "plugins/branchyard/capabilities.json").read_text())["skills"],
    }


def join_and(items):
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def profile_table(profiles):
    """docs/status.md's harness table: one row per profile, the live run, and the two gates Branchyard answers."""
    rows = [
        "| Harness | Profile | Status | Live run (local process) | Permissions answered | Steer |",
        "|---|---|---|---|---|---|",
    ]
    for p in profiles:
        live = p.get("live")
        if live:
            result = f"{live['passed']} of {live['total']} pass"
            run = f"{result}, {live['date']}, {live['version']} ([report]({live['report']}))"
        else:
            run = "not run" if p["profile"] else "\u2014"
        profile = f"`{p['profile']}` ({p['role']})" if p["profile"] else "none"
        rows.append(
            f"| {p['harness']} | {profile} | {p['status']} | {run} | {p['permissions_answered']} | {p['steer']} |"
        )
    return "\n\n" + "\n".join(rows) + "\n\n"


def profile_summary(profiles):
    counts = Counter(p["status"] for p in profiles if p["profile"])
    targets = {p["id"] for p in profiles}
    covered = {p["id"] for p in profiles if p["profile"]}
    built = sum(counts.values())
    return (
        f"{built} driver profiles cover {len(covered)} of {len(targets)} harness targets: "
        f"{counts['live-qualified']} live-qualified, {counts['partial']} partial "
        f"and {counts['unqualified']} unqualified."
    )


def regions(facts):
    """Every region name the Markdown may use, with its exact rendering."""
    vendor, derived = facts["vendor"], facts["derivatives"]
    return {
        "document.skills": "\n\n| Skill | Purpose | Requires |\n|---|---|---|\n"
        + "\n".join(
            f"| `{item['id']}` | {item['description']} | "
            + (", ".join(f"`{name}`" for name in item["requires"]) or "none")
            + " |"
            for item in facts["document_skills"]
        )
        + "\n\n",
        "vendor.files": str(vendor["files"]),
        "vendor.sources": join_and([f"{n} from {s}" for s, n in vendor["by_source"].items()]),
        "vendor.scion": str(vendor["by_source"]["scion"]),
        "vendor.patched": str(vendor["patched"]),
        "derivatives.scion": str(derived["scion"]["derivatives"]),
        "derivatives.scion_sources": str(derived["scion"]["sources"]),
        "derivatives.orca": str(derived["orca"]["derivatives"]),
        "derivatives.orca_sources": str(derived["orca"]["sources"]),
        "derivatives.ports": str(derived["ports"]["derivatives"]),
        "derivatives.ports_sources": str(derived["ports"]["sources"]),
        "derivatives.ports_rust": str(derived["ports"]["rust"]),
        "derivatives.ports_catalogs": str(derived["ports"]["catalogs"]),
        "artifact_preview.page_cap": str(facts["artifact_preview"]["page_cap"]),
        "artifact_preview.row_page": str(facts["artifact_preview"]["row_page"]),
        "workspace.crate_count": str(facts["workspace"]["crate_count"]),
        "http.route_count": str(facts["http"]["route_count"]),
        "metrics.count": str(len(facts["metrics"])),
        "metrics.table": metric_table(facts["metrics"]),
        "runtime.strip_prefixes": join_and([f"`{p}*`" for p in facts["runtime"]["strip_prefixes"]]),
        "profiles.summary": profile_summary(facts["profiles"]),
        "profiles.table": profile_table(facts["profiles"]),
        "cli.exit_codes": exit_table(facts["cli"]["exit_codes"]),
        "stage.table": stage_table(facts["stages"]),
    }


def rewrite(text, rendered, problems, name):
    def swap(match):
        key = match.group(1)
        if key not in rendered:
            problems.append(f"{name}: unknown fact region '{key}'")
            return match.group(0)
        return f"<!-- fact:{key} -->{rendered[key]}<!-- /fact -->"

    return REGION.sub(swap, text)


def normalise(path):
    return re.sub(r"\{[^}/]*\}|:[A-Za-z_]+", "{}", path)


def route_documented(route, lines):
    """The route, in full or abbreviated (`/deny` after `…/allow`), is in the text."""
    full = normalise(route)
    short = re.sub(r"^/v1/repos/\{\}", "", full)
    parent, _, leaf = full.rpartition("/")
    parent_short = re.sub(r"^/v1/repos/\{\}", "", parent)
    for line in lines:
        if full in line or (short != full and short in line):
            return True
        if leaf and not leaf.startswith("{"):
            abbreviated = re.search(r"(?:/|…/)" + re.escape(leaf) + r"(?![\w-])", line)
            if abbreviated and (parent in line or (parent_short and parent_short in line)):
                return True
    return False


def coverage(facts):
    """Server routes in neither docs/server.md nor docs/surfaces.md, less the ratchet allowlist."""
    doc = "\n".join((ROOT / "docs" / name).read_text() for name in ("server.md", "surfaces.md"))
    lines = normalise(doc.replace("...", "…")).splitlines()
    missing = {r for r in facts["http"]["routes"] if not route_documented(r, lines)}
    allowed = set()
    if ALLOW.exists():
        allowed = {line.strip() for line in ALLOW.read_text().splitlines() if line.strip() and not line.startswith("#")}
    problems = []
    for route in sorted(missing - allowed):
        problems.append(f"route {route} is documented in neither docs/server.md nor docs/surfaces.md")
    for route in sorted(allowed - missing):
        problems.append(f"tools/docs_facts_allow.txt lists {route}, which is documented or gone now; remove it")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="rewrite docs/facts.json and every fact region")
    mode.add_argument("--check", action="store_true", help="fail when either differs from the code")
    mode.add_argument("--tests", action="store_true", help="print the test count per crate; nothing is written")
    args = parser.parse_args()

    if args.tests:
        counted = test_facts(workspace_crates())
        for name, count in counted["by_crate"].items():
            print(f"{count['tests']:6}  {count['ignored']:4} ignored  {name}")
        print(f"{counted['total']:6}  {counted['ignored']:4} ignored  total")
        return

    facts = compute()
    rendered = regions(facts)
    wanted = json.dumps(facts, indent=2) + "\n"
    problems = []
    used = set()

    if args.write:
        FACTS.write_text(wanted)
    elif not FACTS.exists() or FACTS.read_text() != wanted:
        problems.append("docs/facts.json is stale; run python3 tools/docs_facts.py --write")

    for path in markdown_files():
        name = path.relative_to(ROOT).as_posix()
        text = path.read_text()
        used.update(m.group(1) for m in REGION.finditer(text))
        updated = rewrite(text, rendered, problems, name)
        if updated == text:
            continue
        if args.write:
            path.write_text(updated)
        else:
            problems.append(
                f"{name}: a generated fact was edited by hand or is stale; run python3 tools/docs_facts.py --write"
            )

    if args.check:
        problems += coverage(facts)
    if problems:
        sys.exit("docs facts differ from the code:\n" + "\n".join(f"  {p}" for p in problems))
    print(
        f"docs facts: {len(rendered)} fact kinds, {len(used)} used in the Markdown, "
        f"{facts['http']['route_count']} routes checked."
    )


if __name__ == "__main__":
    main()
